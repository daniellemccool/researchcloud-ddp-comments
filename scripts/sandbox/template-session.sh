#!/usr/bin/env bash
# On the box: a disposable Firefox with an empty profile, to build the release template by hand.
#
#   scripts/sandbox/template-session.sh up        start it (empty profile, locked proxy policy)
#   scripts/sandbox/template-session.sh down      stop and remove it; the profile stays
#   scripts/sandbox/template-session.sh release   stop it, then `desk-template release`
#
# The container reuses the firefox-dmccool service of the rendered compose file (image, proxy
# policy, network) with the profile directory and policy directory swapped for _template ones.
# It sits behind dmccool's own mitm container, which must be running. Its screen is published on
# 127.0.0.1:$TPL_PORT of the box only: from your laptop, `ssh -L 5999:127.0.0.1:5999 desk` and
# open http://127.0.0.1:5999/ .
#
# Environment: DESK (desk root), TPL_USER (pair to borrow, default dmccool), TPL_PORT (5999),
# ZS_VERSION (Zeeschuimer version for release, 1.14.2), PLATFORM (tiktok).
set -euo pipefail

DESK="${DESK:-/data/onlinehate_zeeschuimer/desk}"
BORROW="${TPL_USER:-dmccool}"
PORT="${TPL_PORT:-5999}"
ZS_VERSION="${ZS_VERSION:-1.14.2}"
PLATFORM="${PLATFORM:-tiktok}"
TPL_DIR="$DESK/state/firefox/_template"
POLICY_DIR="$DESK/firefox/policy/_template"
COMPOSE_FILE="$TPL_DIR/compose.yml"
OUT_DIR="$DESK/templates/release"

SUDO=""
[ "$(id -u)" -eq 0 ] || SUDO="sudo"

[[ "$BORROW" =~ ^[a-z][a-z0-9._-]{0,31}$ ]] || { echo "template-session.sh: bad TPL_USER" >&2; exit 2; }
[[ "$PORT" =~ ^[0-9]+$ ]] || { echo "template-session.sh: bad TPL_PORT" >&2; exit 2; }

compose() { $SUDO docker compose --project-name tpl -f "$COMPOSE_FILE" "$@"; }

generate() {
  local rendered="$DESK/docker-compose.yml" block
  [ -f "$rendered" ] || { echo "template-session.sh: $rendered missing; run desk-sessions render" >&2; exit 1; }
  $SUDO mkdir -p "$TPL_DIR" "$POLICY_DIR"
  $SUDO cp "$DESK/firefox/policy/$BORROW/policies.json" "$POLICY_DIR/policies.json"
  block="$(awk -v svc="  firefox-$BORROW:" '
    $0 == svc { p = 1; print; next }
    p && /^[^ ]/ { p = 0 }
    p && /^  [^ ]/ { p = 0 }
    p' "$rendered")"
  [ -n "$block" ] || { echo "template-session.sh: no firefox-$BORROW service in $rendered" >&2; exit 1; }
  {
    echo "# generated by scripts/sandbox/template-session.sh; not for editing"
    echo "services:"
    printf '%s\n' "$block" | sed \
      -e "s#^  firefox-$BORROW:#  firefox-tpl:#" \
      -e "s#container_name: desk-firefox-$BORROW#container_name: desk-firefox-tpl#" \
      -e "/^    depends_on:/d" \
      -e "s#\./state/firefox/$BORROW:#$TPL_DIR:#" \
      -e "s#\./state/mitm/$BORROW:#$DESK/state/mitm/$BORROW:#" \
      -e "s#\./firefox/policy/$BORROW:#$POLICY_DIR:#" \
      -e "s#\"127.0.0.1:[0-9]*:5800\"#\"127.0.0.1:$PORT:5800\"#"
    echo "networks:"
    echo "  net-$BORROW:"
    echo "    external: true"
    echo "    name: desk_net-$BORROW"
  } | $SUDO tee "$COMPOSE_FILE" >/dev/null
}

case "${1:-}" in
  up)
    $SUDO docker inspect -f '{{.State.Running}}' "desk-mitm-$BORROW" 2>/dev/null | grep -qx true \
      || { echo "template-session.sh: desk-mitm-$BORROW is not running (desk-sessions up $BORROW)" >&2; exit 1; }
    # start from an empty profile: take a leftover tpl project down first, then clear the directory
    [ ! -f "$COMPOSE_FILE" ] || compose down
    if $SUDO docker inspect desk-firefox-tpl >/dev/null 2>&1; then
      echo "template-session.sh: desk-firefox-tpl still exists; remove it first" >&2; exit 1
    fi
    $SUDO rm -rf "$TPL_DIR"
    generate
    compose up -d
    echo "template Firefox is up on 127.0.0.1:$PORT of this box."
    echo "From your laptop: ssh -L $PORT:127.0.0.1:$PORT desk   then open http://127.0.0.1:$PORT/"
    ;;
  down)
    [ -f "$COMPOSE_FILE" ] || { echo "nothing to stop: $COMPOSE_FILE does not exist"; exit 0; }
    compose down
    ;;
  release)
    if [ -f "$COMPOSE_FILE" ]; then compose down; fi
    $SUDO "$(dirname "$(readlink -f "$0")")/../../bin/desk-template" release --platform "$PLATFORM" --zeeschuimer-version "$ZS_VERSION" "$TPL_DIR" "$OUT_DIR"
    echo "next: desk-sessions init --desk-root $DESK --repo /opt/ddp-comments --platform $PLATFORM \\"
    echo "        --collector-role src_co_students --admin-role src_co_admin --contact Danielle \\"
    echo "        --template $OUT_DIR/ddp-comments-template-$PLATFORM-$ZS_VERSION.tar"
    ;;
  *)
    echo "usage: template-session.sh up|down|release" >&2
    exit 2
    ;;
esac
